-- Supabase SQL Setup for Advertising System
-- Run these commands in the SQL Editor of your Supabase project

-- Advertisements Table
CREATE TABLE advertisements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  media_url TEXT,
  media_type TEXT DEFAULT 'image',
  active BOOLEAN DEFAULT true,
  website_url TEXT,
  show_qr_code BOOLEAN DEFAULT false,
  qr_type TEXT DEFAULT 'web',
  product_name TEXT,
  product_price DECIMAL(10, 2),
  payment_provider TEXT,
  time_slot_morning BOOLEAN DEFAULT false,
  time_slot_afternoon BOOLEAN DEFAULT false,
  time_slot_night BOOLEAN DEFAULT false,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Create index on the active field for faster queries
CREATE INDEX idx_advertisements_active ON advertisements(active);

-- Schedules Table
CREATE TABLE schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  advertisement_id BIGINT REFERENCES advertisements(id) ON DELETE CASCADE,
  start_time TIMESTAMP WITH TIME ZONE NOT NULL,
  end_time TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Create index on advertisement_id for faster lookups
CREATE INDEX idx_schedules_advertisement_id ON schedules(advertisement_id);

-- Create index on start_time and end_time for schedule queries
CREATE INDEX idx_schedules_time_range ON schedules(start_time, end_time);

